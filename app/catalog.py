def validate_items(subject: str, items: list[str]) -> list[str] | None:
    """Проверяет, что все элементы существуют и относятся к предмету. Убирает дубли."""
    if subject not in SUBJECTS:
        return None
    seen: list[str] = []
    for iid in items:
        item = ITEMS.get(iid)
        if item is None or item["subject"] != subject:
            return None
        if iid not in seen:
            seen.append(iid)
    return seen or None


def public_catalog(assistant_name: str) -> dict:
    """Статический каталог для фронтенда (ключей и секретов здесь нет)."""
    return {
        "assistant": assistant_name,
        "subjects": SUBJECTS,
        "items": [{k: v for k, v in it.items() if k != "ai"} for it in ITEMS.values()],
        "presets": PRESETS,
        "events": {
            eid: {"subject": ev["subject"], "requires": ev["requires"], "eq": ev["eq"],
                  "text": {"ru": ev["ru"], "kk": ev["kk"]}}
            for eid, ev in EVENTS.items()
        },
    }
